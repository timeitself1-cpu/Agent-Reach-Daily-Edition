def test_a_carried_over_story_keeps_its_section_unless_new_reporting_arrives():
    from agent_reach.daily.changes import keep_previous_categories
    from tests.daily_fakes import make_story

    tool_url, beam_url = "https://arstechnica.test/apple-intelligence-tool", "https://reflection.test/beam"
    previous = _edition_on(5, [
        make_story(headline="Tool Removes Apple's AI Bloatware and Frees up Storage on macOS", category="Tech",
                   url=tool_url),
        make_story(headline="Beam: Reflection's 501B Open-Weight Model", category="Science & AI", url=beam_url)])
    tool = make_story(headline="Command-line Tool Quickly Removes Apple Intelligence from macOS 27",
                      category="Science & AI", url=tool_url)
    beam = make_story(headline="Beam: Reflection's 501B Open-Weight Model", category="Tech", url=beam_url)
    assert keep_previous_categories([tool, beam], previous) == 2
    assert (tool.category.value, beam.category.value) == ("Tech", "Science & AI")

    grown = _with_report(make_story(headline="Beam: Reflection's 501B Open-Weight Model", category="Tech",
                                    url=beam_url), "The Verge", "Reflection releases Beam, a 501B open model")
