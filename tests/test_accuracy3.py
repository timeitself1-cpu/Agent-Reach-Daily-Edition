def test_new_reporting_or_a_headline_from_new_reports_is_an_update():
    from agent_reach.daily.changes import compare_editions, headline_has_news
    from tests.daily_fakes import make_story

    url = "https://bbc.test/bombers"
    before = make_story(headline="US Bombers Removed from UK Base Due to Iranian Threat", url=url)
    after = _with_report(make_story(headline="US Bombers Removed from UK Base Due to Iranian Threat", url=url),
                         "New York Times", "Potential Iranian Drone Attack Led to Exit of U.S. Aircraft From British Air Base")
    ch = compare_editions(_edition_on(5, [before]), _edition_on(6, [after]))
    assert [c.detail for c in ch.updated] == ["new reporting from The New York Times"]

    old = make_story(headline="Trump Approval Ratings Plummet to New Low", url="https://guardian.test/polls")
    new = _with_report(make_story(headline="Trump Claims He's 'Doing Great' Amid Record Low Approval Rating",
                                  url="https://guardian.test/polls"),
                       "Wire One", "Trump claims he's 'doing great' as his approval rating sinks to record low")
    assert headline_has_news(new, old)
    reworded = make_story(headline="Trump Approval Hits Record Low in New Polls", url="https://guardian.test/polls")
    assert not headline_has_news(reworded, old)

    # a second rc10 run: the new headline is a title the previous edition already cited
    nobel_url = "https://ap.test/nobel"
    nobel = _with_report(make_story(headline="Scientists Win Nobel Prize for Optogenetics", url=nobel_url),
                         "Science - News", "Method for controlling brain cells with light wins Nobel")
    retitled = _with_report(_with_report(make_story(headline="Method for Controlling Brain Cells with Light Wins Nobel",
                                                    url=nobel_url),
                                         "Science - News", "Method for controlling brain cells with light wins Nobel"),
                            "Phys.org", "California scientist wins a Nobel Prize, then makes school lunches for his kids")
    retitled.evidence[1].url = nobel.evidence[1].url
    assert not headline_has_news(retitled, nobel)
    ch = compare_editions(_edition_on(5, [nobel]), _edition_on(6, [retitled]))
    assert [c.detail for c in ch.updated] == ["new reporting from Phys.org"]


