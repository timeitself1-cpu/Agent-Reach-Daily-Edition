def test_cloud_runner_gives_the_daily_refresh_a_cpu_sized_budget():
    import re
    from pathlib import Path

    from agent_reach.daily.prefs import DailyPrefs

    text = (Path(__file__).resolve().parents[1] / ".github" / "workflows" / "cloud-runner.yml").read_text("utf-8")
    articles = int(re.search(r"daily_articles \|\| '(\d+)'", text).group(1))
