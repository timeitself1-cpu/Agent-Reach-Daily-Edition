    prefs = DailyPrefs(max_items_for_llm=articles, max_run_minutes=minutes)  # within the settings' bounds
    assert prefs.max_items_for_llm < DailyPrefs().max_items_for_llm and minutes + 10 <= job_timeout
    assert "prefs.max_items_for_llm = int(os.environ[\"DAILY_ARTICLES\"])" in text
