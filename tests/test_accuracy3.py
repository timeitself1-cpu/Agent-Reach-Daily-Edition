def test_reddit_health_note_names_the_subreddit_not_its_url():
    import asyncio

    import httpx

    from agent_reach.config import Settings
    from agent_reach.ingestion.social import RedditIngester
    from tests.daily_fakes import RealAsyncClient

    entries = "".join(f"<entry><title>Big news story {i} today</title><link href='https://www.reddit.com/r/news/{i}'/>"
                      f"<category term='news'/></entry>" for i in range(3))
    atom = f'<?xml version="1.0"?><feed xmlns="http://www.w3.org/2005/Atom">{entries}</feed>'.encode()

    def handler(req):
        if req.url.path.endswith(".json"):
            return httpx.Response(403)
        if "worldnews" in req.url.path or "technology" in req.url.path:
            return httpx.Response(429, headers={"Retry-After": "0"})
        return httpx.Response(200, content=atom)

    settings = Settings(reddit_subreddits=["news", "worldnews", "technology"], reddit_max_retries=0,
                        reddit_request_spacing_s=0.0, http_backoff_base_s=0.01)

    async def go():
        async with RealAsyncClient(transport=httpx.MockTransport(handler)) as client:
            return await RedditIngester(client, settings, asyncio.Semaphore(2)).run()

    items, stat = asyncio.run(go())
    assert stat.ok and items
    # one cause, every subreddit it hit: the note fits instead of being cut mid-URL
    assert "r/worldnews, r/technology: HTTPStatusError: HTTP 429" in stat.error and "https://" not in stat.error


