def _index() -> LinkIndex:
    """The morning stories inside a run of realistic size (a word in 30 of 1,000 items is not rare)."""
    rng = random.Random(1)
    words = ["".join(rng.choice("bcdfghklmnprstvz") + rng.choice("aeiou") for _ in range(4)) for _ in range(3000)]
    padding = [("news_rss", " ".join(rng.sample(words, 6)), "") for _ in range(1000)]
    # 'games' was in 17 of the run's 1,352 titles (sports and gaming): as common here
    padding += [("news_rss", " ".join(rng.sample(words, 5)) + " games", "") for _ in range(15)]
    items = []
    for i, (source, title, ctx) in enumerate(MORNING + REAL + padding, start=1):
        raw = RawTrendItem(title=title, source=SourceName(source), timestamp=NOW)
        items.append(CleanedTrendItem(**raw.model_dump(), item_id=i, normalized_title=title, heuristic_score=0.6,
                                      context=ctx or None))
    return LinkIndex(items, items)


INDEX = _index()


def _groups(ids: list[int]) -> list[list[int]]:
    return sorted((sorted(g) for g in INDEX.components(ids, [])), key=lambda g: (-len(g), g))


def _groups_embedded(ids: list[int]) -> list[list[int]]:
    """Grouping when the embedding model agrees that the reports are close (identical vectors)."""
    gate = IdentityGate(INDEX, {i: [1.0] for i in ids})
    return sorted((sorted(g) for g in cohesive_groups(ids, gate)), key=lambda g: (-len(g), g))


